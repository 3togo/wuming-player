import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
const root = process.env.WUMING_SOURCE_ROOT || resolve(import.meta.dirname, '../..');
const load = async file => import('data:text/javascript;base64,' + readFileSync(resolve(root, file)).toString('base64'));
const lib = 'libraries/js-runtime/src/main/resources/js/lib/';
const cat = await load(lib + 'cat.js');
assert.equal(cat.Crypto.SHA256('abc').toString(), 'ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad');
assert.equal(cat.load('<div><b>hello</b></div>')('div b').text(), 'hello');
assert.deepEqual(cat.jp('$.items[*].id', {items:[{id:1},{id:2}]}), [1,2]);
assert.equal(cat.jinja2('Hello {{ name }}', {name:'world'}), 'Hello world');
assert.equal(cat._.get({a:{b:3}}, 'a.b'), 3);
assert.equal(cat.dayjs('2020-01-02').format('YYYY-MM-DD'), '2020-01-02');
const gbk = (await load(lib + 'gbk.js')).gbkTool();
assert.equal(gbk.encode('中文 test'), '%D6%D0%CE%C4%20test');
assert.equal(gbk.decode('%D6%D0%CE%C4%20test'), '中文 test');
const similarity = await load(lib + 'similarity.js');
assert.equal(similarity.compareTwoStrings('hello', 'hello'), 1);
assert.equal(similarity.findBestMatch('alpha', ['beta', 'alpha']).bestMatchIndex, 1);
assert.deepEqual(similarity.findBestLCS('abcdef', ['abXXef', 'cde']).bestMatch.lcs, {length:3, sequence:'cde', offset:2});
console.log('JS compatibility checks passed: crypto, DOM, JSONPath, templates, dates, GBK, similarity.');
