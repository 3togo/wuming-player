#!/usr/bin/env python3
"""Generate platform adapters from design-core's canonical tokens; --check detects drift."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CORE = ROOT / "libraries/design-core"


def snake(value):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", value).lower()


def outputs():
    data = json.loads((CORE / "design-tokens.json").read_text())
    palettes, metrics = data["palettes"], data["metrics"]
    roles = list(palettes["CLASSIC_DARK"])
    for palette in palettes.values():
        assert list(palette) == roles, "All palettes must implement every semantic role"
        assert all(re.fullmatch(r"[0-9A-F]{6}", v) for v in palette.values())
    assert all(isinstance(v, int) and v > 0 for v in metrics.values())
    header = "// Generated by scripts/generate-design-tokens.py; edit design-tokens.json.\n"
    kotlin = header + "package com.wuming.tv.core.design\n\n"
    kotlin += "data class ThemePalette(\n" + "".join(f"    val {r}: Int,\n" for r in roles) + ")\n\n"
    kotlin += "object DesignTokens {\n"
    kotlin += "".join(f"    const val {snake(k).upper()} = {v}\n" for k, v in metrics.items())
    for name, palette in palettes.items():
        kotlin += f"    val {name} = ThemePalette(\n"
        kotlin += "".join(f"        {r} = 0xFF{v}.toInt(),\n" for r, v in palette.items()) + "    )\n"
    kotlin += "}\n"
    result = {CORE / "src/main/kotlin/com/wuming/tv/core/design/DesignTokens.kt": kotlin}
    # Android retains a dark Aurora canvas until legacy white artwork labels are migrated.
    # Classic Android keeps its wallpaper contract; desktop consumes all four palettes.
    for qualifier, name in [("values", "AURORA_DARK")]:
        xml = '<?xml version="1.0" encoding="utf-8"?>\n<resources>\n'
        xml += "    <!-- Generated by scripts/generate-design-tokens.py; do not edit. -->\n"
        xml += "".join(f'    <color name="ds_{snake(r)}">#{v}</color>\n' for r, v in palettes[name].items())
        for percent, alpha in [(80, "CC"), (70, "B3"), (60, "99"), (50, "80"), (40, "66")]:
            xml += f'    <color name="ds_accent_{percent}">#{alpha}{palettes[name]["accentStrong"]}</color>\n'
        if qualifier == "values":
            xml += "".join(f'    <dimen name="ds_{snake(k)}">{v}{"sp" if k.endswith("Text") else "dp"}</dimen>\n' for k, v in metrics.items())
        result[ROOT / f"app/src/main/res/{qualifier}/design_tokens.xml"] = xml + "</resources>\n"
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, content in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale:
        raise SystemExit("Run python3 scripts/generate-design-tokens.py; stale: " + ", ".join(stale))
    print("Design tokens verified." if args.check else "Design tokens generated.")


if __name__ == "__main__":
    main()
